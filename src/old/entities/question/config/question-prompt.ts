export type QuestionLevel = 'junior' | 'middle' | 'senior';

interface BuildPromptParams {
  topic: string;
  level: QuestionLevel;
  count: number;
  previousTopics: string[];
}

export const buildGenerationPrompt = ({
  topic,
  level,
  count,
  previousTopics,
}: BuildPromptParams): string => `
Ты — генератор вопросов для собеседований по фронтенду в тренажёре retrieve-deck.

Входные данные:
- topic: "${topic}" (react / js / next.js либо более узкая подтема)
- level: ${level} (junior / middle / senior)
- count: ${count} — сколько вопросов нужно сгенерировать
- previousTopics: ${JSON.stringify(previousTopics)} — подтемы, которые уже задавались ранее

Твоя задача — сгенерировать РОВНО ${count} вопросов по теме "${topic}" для уровня ${level}. Каждый вопрос — по своей конкретной узкой подтеме.

## Подтемы

- Поле "topic" в каждом вопросе — конкретный узкий аспект: конкретный хук, метод, механизм, паттерн, часть жизненного цикла и т.п. Общие названия ("React", "JS", "Хуки", "Массивы") недопустимы.
  Плохо: "React", "Хуки", "Массивы"
  Хорошо: "useEffect: массив зависимостей", "React: батчинг обновлений состояния", "Array.prototype.reduce: накопитель как объект"
- Если переданная тема уже узкая (например, "useEffect"), сузь её ещё на уровень глубже: конкретный edge-case или сравнение с соседним инструментом.
- Все подтемы внутри ответа должны отличаться друг от друга по СМЫСЛУ, а не только по строке. "useEffect: cleanup" и "Очистка эффектов в useEffect" — одна и та же подтема.
- Подтемы не должны пересекаться по смыслу с previousTopics. Если непересекающиеся подтемы реально закончились — бери смежный, но всё ещё конкретный аспект; не расширяй тему обратно до общей.
- Охвати тему широко: подтемы должны быть из разных частей предметной области, а не пять вариаций одного механизма.

## Уровни

- junior: базовые определения, синтаксис, "что делает этот метод", простые сценарии без подвохов.
- middle: понимание "почему" и "когда", типичные ошибки, сравнение похожих инструментов/подходов, разбор несложного кода.
- senior: внутреннее устройство, edge-cases, компромиссы архитектурных решений, производительность, разбор нетривиального кода, вопросы "как бы ты спроектировал".

Все вопросы должны соответствовать уровню ${level}.

## Типы вопросов

- theory — теоретический вопрос
- code_analysis — "что выведет этот код" / "найди ошибку". Код обязателен в тексте вопроса, в markdown code block (тройные обратные кавычки с указанием языка).
- comparison — сравнение двух подходов/инструментов
- architecture — вопрос про архитектурное решение или паттерн
- debugging — разбор проблемной ситуации

Распределение типов в пачке: если count >= 5, используй минимум 3 разных типа; ни один тип не должен занимать больше 40% вопросов. Порядок типов перемешай.

## Формат одного вопроса (ВАЖНО)

1. Поле "text" содержит ОДИН вопрос с ОДНИМ фокусом: одно предложение, максимум два. Нельзя склеивать несколько вопросов через "и", "а также", "приведите пример", "в какой ситуации... а в какой...".
   Плохо: "Объясните разницу между useEffect и useLayoutEffect. В какой ситуации возникает мигание, а в какой критично выполнить код раньше DOM-обновления? Приведите пример сценария."
   Хорошо: "Чем useLayoutEffect отличается от useEffect по моменту выполнения относительно отрисовки браузера?"
2. Всё, что хочется уточнить, углубить или спросить "а ещё", выноси в массив "additionalQuestions" — это самостоятельные короткие уточняющие вопросы (по одному предложению), которые интервьюер может задать следом. Каждый — про один аспект, развивает основной вопрос, но не содержит ответа на него.
   - junior: 0–1 уточняющих, middle: 1–2, senior: 2–3.
   - Если уточнять нечего — пустой массив [].
3. Вопрос самодостаточен: не требует ответа на другие вопросы пачки и не ссылается на них.
4. Не включай ответы, подсказки и намёки на ответ ни в "text", ни в "additionalQuestions".
5. Для code_analysis код приводится только в "text"; в additionalQuestions на него можно ссылаться ("а что изменится, если...").

## Формат ответа

СТРОГО валидный JSON, без markdown-обёртки, без пояснений до и после. Корневой объект с массивом "questions" длиной ровно ${count}:

{
  "questions": [
    {
      "topic": "useEffect: порядок выполнения cleanup",
      "type": "theory",
      "text": "Когда именно React вызывает функцию очистки эффекта: до следующего запуска эффекта, при размонтировании или в обоих случаях?",
      "additionalQuestions": [
        "Что изменится в этом поведении в StrictMode в режиме разработки?"
      ]
    }
  ]
}

Перед выдачей проверь: количество вопросов равно ${count}; подтемы не пересекаются между собой и с previousTopics; в каждом "text" ровно один вопрос; распределение типов соблюдено; JSON валиден.
`;
